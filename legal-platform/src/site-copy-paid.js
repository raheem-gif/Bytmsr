/** مواضيع الأفراد والشركات (G11-26 من segment.js): الاسم، والسطر الشارح لـ«موضوع آخر» فقط (السطر الفارغ يمسح سطر «خيري») */
function topicsPaid() {
  const out = {};
  for (const t of TOPICS) {
    const p = PAID_TOPICS[t.key];
    if (p) out[t.key] = { label: p.label, sub: p.sub || '' };
  }
  return out;
}

/**
 * جمل واتساب الجاهزة (G11-41) مضغوطة: h + (b + p[key]) + «.» = paidWaPrefill(key) حرفيًا (الجملة التي يتعرف عليها الخادم،
 * segment.js) — بلا تكرار الجملة الطويلة ثماني مرات في الصفحة.
 */
function waPaid() {
  const p = {};
  for (const t of TOPICS) if (PAID_TOPICS[t.key]?.wa_phrase) p[t.key] = PAID_TOPICS[t.key].wa_phrase;
  return { h: PAID_PREFILL_HEAD, b: ' بخصوص ', p };
}

/** نفس تركيب intake.js للجملة (للاختبار: يساوي paidWaPrefill لكل موضوع وبلا موضوع) */
export function waFrom(wa, key) {
  return `${wa.h}${wa.p[key] ? wa.b + wa.p[key] : ''}.`;
}

