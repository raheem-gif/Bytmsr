// إخفاء البيانات الشخصية قبل إدخال الحالة في قاعدة المعرفة المؤسسية.
// إخفاء آلي «أولي» يُراجَع دائمًا من الإدارة قبل اعتماد الحالة للاستخدام المعرفي أو التدريبي.
import { latinDigits } from '../util.js';

const STOP_NAME_PARTS = new Set(['عبد', 'على', 'علي', 'ابو', 'أبو', 'بن', 'بنت', 'ال', 'الله', 'محمد', 'احمد', 'أحمد']);

// «المتوفى» ليست لقبًا يسبق الاسم في الصياغة القانونية بل صفة («الابن المتوفى قبل أبيه»)، فلا تُعد هنا؛
// و«المرحوم/المرحومة» تغطي ذكر المتوفى باسمه.
const KIN = '(?:اخويا|أخويا|اخوي|أخوي|أخي|اخي|اختي|أختي|ابني|إبني|بنتي|ابويا|أبويا|أبي|ابي|والدي|والدتي|امي|أمي|زوجي|زوجتي|جوزي|مراتي|عمي|عمتي|خالي|خالتي|جدي|جدتي|طليقي|طليقتي|المرحوم|المرحومة|المرحومه|المدعو|المدعوة|السيد|السيدة|الحاج|الحاجة|الأستاذ|الاستاذ|الأستاذة|الاستاذة|المهندس|الدكتور)';

// كلمات عامة قد تلي صلة القرابة أو اللقب وليست أسماء: أفعال وضمائر وحروف جر وظروف، ومسميات القرابة والمراكز القانونية
// (تُقارن بعد حذف الحركات والتنوين: «أبناءً» ← «أبناء»)
const COMMON_AFTER_KIN = new RegExp(
  '^(?:' +
    [
      'الله|رحمه|رحمها|يرحمه|يرحمها|عنده|عندها|كان|كانت|قال|قالت|اللي|الذي|التي|ده|دي|هو|هي|و|بقى|بقت',
      'مات|ماتت|توفي|توفيت|اتوفى|اتوفت|متوفي|متوفى|ساكن|ساكنة|عايش|عايشة|رافض|رافضة|مسافر|مسافرة',
      'في|من|على|علي|قبل|بعد|منذ|عن|عنه|عنها|دون|بدون|إلى|الى|حتى|عليه|عليها|له|لها|مع|بين|إن|ان|أن|انه|أنه|لأن|لان|لم|لا|ما|قد|كل|أيضا',
      'أبناء|ابناء|أبناءه|أبنائه|بنات|ذكور|ذكورا|إناث|اناث|إناثا|اناثا|أولاد|اولاد|ولاد|أحفاد|احفاد|ورثة|الورثة|الوارث|المورث|المورثة',
      'الابن|الإبن|الابنة|البنت|الأخ|الاخ|الأخت|الاخت|الزوج|الزوجة|الأب|الاب|الأم|الام|الجد|الجدة|القاصر|القاصرة|القاصرين|القصر',
      'المتوفى|المتوفي|المتوفاة|المرحوم|المرحومة|أبيه|ابيه|أبيها|ابيها|أمه|امه|أمها|امها|والده|والدته|والدها|والدتها|زوجها|زوجته',
    ].join('|') +
    ')$',
);
// «السيدة زينب» و«السيدة نفيسة»… أسماء أحياء ومساجد في القاهرة وليست أشخاصًا
const SAINT_PLACES = /^(?:زينب|نفيسة|نفيسه|عائشة|عائشه|سكينة|سكينه|رقية|رقيه)$/;
const stripMarks = (w) => String(w || '').trim().replace(/\p{M}/gu, '');
// ألقاب مختصرة: يجب أن تكون كلمة مستقلة تمامًا
const ABBR = '(?:أ\\.|د\\.|م\\.)';

// ───────────── v9.1 fixes: أسماء الأبناء والأسرة المذكورة في الوقائع ─────────────
const FAMILY_TERMS =
  '(?:أطفال|اطفال|أولاد|اولاد|ولاد|عيال|أبناء|ابناء|طفلان|طفلين|طفلتان|طفلتين|طفل|طفلة|قاصران|قاصرين|قاصرتين|قصر|قاصر|قاصرة|ابن|ابنة|بنت|بنات|ولد|ابني|بنتي|ابنها|بنتها|ابنه|بنته|إخوة|اخوة|أشقاء|اشقاء|ورثة|الورثة)';
const NOT_NAMES = new Set([
  'صغار', 'صغير', 'صغيرة', 'كبار', 'قصر', 'قاصر', 'قاصرة', 'قاصرين', 'سنة', 'سنه', 'سنين', 'سنوات', 'شهور', 'أشهر', 'اشهر', 'عمر', 'عمره', 'عمرها',
  'ولد', 'ولدين', 'بنت', 'بنتين', 'ذكر', 'أنثى', 'انثى', 'توأم', 'توام', 'تقريبا', 'تقريبًا', 'حاليا', 'حاليًا', 'فقط', 'كلهم', 'منهم', 'معاها', 'معاه',
]);
/** كلمة تصلح اسمًا علمًا: 3 حروف على الأقل، ليست كلمة شائعة ولا معرّفة بـ«ال» ولا رقمًا */
function nameLike(w) {
  const x = stripMarks(w);
  return /^\p{L}{3,}$/u.test(x) && !/^ال/.test(x) && !NOT_NAMES.has(x) && !COMMON_AFTER_KIN.test(x);
}
function splitNames(list) {
  return String(list)
    .replace(/\s+و(?=\p{L})/gu, '،')
    .split(/[،,\s]+/)
    .filter(nameLike);
}
/**
 * أسماء الأبناء/الأسرة المذكورة صراحة في نص (لتُخفى أينما وردت في سجل المعرفة):
 * «طفلان قاصران (يوسف ومريم)»، «شهادات ميلاد يوسف ومريم»، والكنية «أم يوسف» ← «يوسف».
 */
export function familyNames(text) {
  const s = String(text || '');
  const out = new Set();
  for (const m of s.matchAll(new RegExp(`${FAMILY_TERMS}[^()\\n]{0,25}\\(([^()\\n]{2,80})\\)`, 'gu'))) for (const n of splitNames(m[1])) out.add(n);
  for (const m of s.matchAll(/شهاد(?:ة|ه|ات|تي|ات)\s+(?:ال)?ميلاد\s+(\p{L}{3,}(?:\s*(?:،|,|و)\s*\p{L}{3,}){0,5})/gu)) for (const n of splitNames(m[1])) out.add(n);
  // («ام» بلا همزة قد تكون «أو» في الكلام الدارج، فلا تُعد كنية)
  for (const m of s.matchAll(/(?:^|[^\p{L}])(?:أم|أبو|ابو)\s+(\p{L}{3,})/gu)) if (nameLike(m[1])) out.add(m[1]);
  return [...out];
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** نمط متسامح مع اختلاف الكتابة الشائع: ة/ه، أ/إ/آ/ا، ى/ي، والمسافة في «عبد ال...» */
function tolerantName(name) {
  return escapeRe(name)
    .replace(/[ةه]/g, '[ةه]')
    .replace(/[اأإآ]/g, '[اأإآ]')
    .replace(/[ىي]/g, '[ىي]')
    .replace(/\s+/g, '\\s*');
}

/**
 * gate K12/J-21: رقم «يشبه الهاتف» فعلًا — يبدأ بـ + أو 00 أو 0، أو رقم محمول مصري دولي بلا + (2010…)؛
 * رقم فاتورة أو قيد مثل 20261234567 ليس هاتفًا (يُستخدم مع strictPhones في نصوص ملفات الشركات)
 */
function phoneShaped(t) {
  const d = t.replace(/[\s-]/g, '');
  return /^(?:\+|00|0)/.test(d) || /^201[0125]\d{8}$/.test(d);
}

/**
 * @param {string} text
 * @param {{ names?: string[], strictPhones?: boolean }} opts أسماء معروفة (العميل، المحامون) تُخفى أينما وردت؛
 *   strictPhones: لا يُعد هاتفًا إلا ما يشبه الهاتف (ملفات الشركات: أرقام الفواتير والقيود تبقى)
 * @returns {{ text: string, counts: object }}
 */
export function redact(text, { names = [], strictPhones = false } = {}) {
  if (!text) return { text: text || '', counts: {} };
  const counts = {};
  const bump = (k, by = 1) => (counts[k] = (counts[k] || 0) + by);
  // نعمل على نسخة بأرقام لاتينية (نفس الطول) حتى تُكتشف الأرقام العربية-الهندية أيضًا
  let s = latinDigits(String(text));

  const rep = (re, label, key) => {
    s = s.replace(re, (...m) => {
      bump(key);
      return typeof label === 'function' ? label(...m) : label;
    });
  };

  rep(/[\w.+-]+@[\w-]+\.[\w.-]+/g, '[بريد إلكتروني]', 'emails');
  rep(/https?:\/\/\S+/g, '[رابط]', 'links');
  // v9.1 fixes: روابط بلا بروتوكول (wa.me/… و www.… و legal.example.org/p/…) ورابط صفحة المتابعة النسبي /p/<رمز>
  rep(/\b(?:www\.|wa\.me\/)\S+/gi, '[رابط]', 'links');
  rep(/\b(?:[a-z0-9-]+\.)+(?:com|org|net|eg|me|io|info|gov|edu|app|link|ly|co|ai|site|online|xyz)(?:\.[a-z]{2})?(?:\/\S*)?(?![\w.-])/gi, '[رابط]', 'links');
  rep(/\/p\/[A-Za-z0-9_-]{8,}/g, '[رابط]', 'links');
  rep(/\b[23]\d{13}\b/g, '[رقم قومي]', 'national_ids');
  s = s.replace(/(?:\+|00)?\d[\d\s-]{7,16}\d/g, (m) => {
    const t = m.trim();
    const digits = t.replace(/\D/g, '').length;
    // التواريخ (2026-11-15) والأرقام القصيرة ليست هواتف
    if (/^\d{4}-\d{1,2}-\d{1,2}$/.test(t) || /^\d{1,2}-\d{1,2}-\d{4}$/.test(t) || digits < 8 || digits > 15) return m;
    if (strictPhones && !phoneShaped(t)) return m;
    bump('phones');
    return '[رقم هاتف]';
  });
  rep(/\b(?:[A-Z]{2,3})-\d{4}-\d{5}\b|\bCL-\d{5}\b/g, '[رقم ملف]', 'codes');
  // v9.1 fixes: «ش.» / «ش» / «شارع» كلمة مستقلة فقط (لا نهاية «المعاش.»)، ومعها رقم المبنى قبلها إن وُجد («12 ش التحرير»)
  s = s.replace(/(^|[^\p{L}\p{M}\d])(?:\d{1,4}\s*)?(?:شارع|ش\.?)\s+[^\s،.,]+(?:\s+[^\s،.,]+){0,2}/gu, (m, pre) => {
    bump('addresses');
    return `${pre}[عنوان]`;
  });
  rep(/(?:عمارة|عماره|برج|شقة|شقه)\s+رقم\s*\d+/g, '[عنوان]', 'addresses');

  // الأسماء المعروفة: الاسم الكامل ثم الاسم الثنائي ثم الاسم الأول (إن لم يكن شائعًا جدًا)
  const variants = new Set();
  for (const full of names.filter(Boolean)) {
    const clean = String(full).replace(/^(?:أ\.|د\.|م\.|الأستاذ|الاستاذ|الأستاذة|الاستاذة)\s*/, '').trim();
    if (!clean) continue;
    const parts = clean.split(/\s+/);
    variants.add(clean);
    if (parts.length >= 2) variants.add(parts.slice(0, 2).join(' '));
    if (parts[0].length >= 4 && !STOP_NAME_PARTS.has(parts[0])) variants.add(parts[0]);
  }
  for (const nm of [...variants].sort((a, b) => b.length - a.length)) {
    // (v9.1 fixes: ومع حرف العطف أو الجر الملتصق: «يوسف ومريم» ← «[اسم] و[اسم]»)
    // gate K2/J-04: الاسم الأول وحده يقبل حرف العطف (و/ف) فقط، لا حرف الجر الملتصق (ل/ب): «لدينا» ليست «ل» + «دينا»
    const clitic = /\s/.test(nm) ? '[وفبل]?' : '[وف]?';
    const re = new RegExp(`(^${clitic}|[^\\p{L}]${clitic})${tolerantName(nm)}(?=$|[^\\p{L}])`, 'gu');
    s = s.replace(re, (m, pre) => {
      bump('names');
      return `${pre}[اسم]`;
    });
  }

  // اسم يلي صلة قرابة أو لقبًا: «أخويا محمود» ← «أخويا [اسم]»
  // الصلة أو اللقب يجب أن يكون كلمة مستقلة (وإلا اعتُبرت «الحكم.» لقب «م.»)
  // الحركات والتنوين (\p{M}) جزء من الكلمة حتى لا تنقسم «أبناءً» إلى «أبناء» + «ً»
  // gate K2/J-03: اللقب المختصر («م.») لا يُعد لقبًا بعد نقطة أو حرف مختصر آخر — نهاية «ش.م.م.» و«ش.ذ.م.م.» صيغة شركة —
  // والاسم بعد اللقب على السطر نفسه (لا يبتلع سطرًا تاليًا مثل «الطرف الآخر:»)
  const kinRe = new RegExp(`(^|[^\\p{L}\\p{M}.])((?:[وف]?${KIN})|(?<!\\p{L}\\.\\s?)${ABBR})[^\\S\\n]+(?!\\[)([\\p{L}\\p{M}]{3,})([^\\S\\n]+(?!\\[)(?:عبد[^\\S\\n]*)?[\\p{L}\\p{M}]{3,})?`, 'gu');
  s = s.replace(kinRe, (m, pre, kin, first, second) => {
    // لا نخفي الكلمات العامة التي تلي صلة القرابة
    const isCommon = (w) => COMMON_AFTER_KIN.test(stripMarks(w));
    if (isCommon(first)) return m;
    if (/^[وف]?السيد[ةه]$/.test(kin) && SAINT_PLACES.test(stripMarks(first))) {
      // اسم المكان يبقى؛ وإن تلاه اسم (لا كلمة عامة ولا كلمة معطوفة بالواو أو الفاء) فهو اسم شخص يُخفى
      if (!second || isCommon(second) || /^\s*[وف]/.test(second)) return m;
      bump('names');
      return `${pre}${kin} ${first} [اسم]`;
    }
    bump('names');
    const keepSecond = second && isCommon(second) ? second : '';
    return `${pre}${kin} [اسم]${keepSecond}`;
  });

  return { text: s, counts };
}
